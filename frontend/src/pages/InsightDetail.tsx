import { Link, useParams } from 'react-router-dom';
import { ApiError, apiClient } from '../api/client';
import { useApi } from '../hooks/useApi';
import Badge from '../components/ui/Badge';
import Card from '../components/ui/Card';
import ErrorState from '../components/ui/ErrorState';
import Evidence from '../components/Evidence';
import Loading from '../components/ui/Loading';

type Loose = Record<string, unknown>;

function str(value: unknown): string | null {
  return typeof value === 'string' && value ? value : null;
}

function formatConfidence(value: unknown): string {
  if (typeof value !== 'number' || !Number.isFinite(value)) return '—';
  return value <= 1 ? `${Math.round(value * 100)}%` : String(value);
}

function formatDate(value: unknown): string {
  const raw = str(value);
  if (!raw) return '—';
  const time = new Date(raw).getTime();
  return Number.isNaN(time) ? raw : new Date(time).toLocaleString();
}

function metricEntries(value: unknown): Array<[string, string]> {
  if (!value || typeof value !== 'object' || Array.isArray(value)) return [];
  return Object.entries(value as Loose).map(([key, val]) => [
    key,
    typeof val === 'object' ? JSON.stringify(val) : String(val),
  ]);
}

/** Insight detail: badges, meta table, evidence, related metrics, back link. */
export default function InsightDetail() {
  const { id = '' } = useParams();
  const insight = useApi(() => apiClient.getInsight(id), [id]);

  if (insight.loading) {
    return (
      <div>
        <h1>Insight</h1>
        <Loading />
      </div>
    );
  }

  // 404 and backend-DOWN both land here with a way back to the list.
  if (insight.error || !insight.data) {
    const message =
      insight.error instanceof ApiError && insight.error.status === 404
        ? 'Insight not found'
        : (insight.error?.message ?? 'Insight not found');
    return (
      <div>
        <h1>Insight</h1>
        <ErrorState message={message} />
        <p>
          <Link to="/app/insights">← Back to insights</Link>
        </p>
      </div>
    );
  }

  const item = insight.data;
  const extra = item as unknown as Loose;
  const metrics = metricEntries(extra.source_metrics);

  return (
    <div>
      <h1>{item.title || 'Untitled insight'}</h1>
      <p>
        {item.severity && <Badge severity={item.severity}>{item.severity}</Badge>}{' '}
        {item.category && <span className="badge">{item.category}</span>}{' '}
        {item.status && <span className="badge">{item.status}</span>}
      </p>
      {item.description && <p className="page-sub">{item.description}</p>}
      <Card title="Details">
        <table className="meta-table">
          <tbody>
            <tr>
              <th scope="row">Created</th>
              <td>{formatDate(extra.created_at ?? extra.detected_at)}</td>
            </tr>
            <tr>
              <th scope="row">Confidence</th>
              <td>{formatConfidence(item.confidence)}</td>
            </tr>
            <tr>
              <th scope="row">Generated by</th>
              <td>{str(extra.generated_by) ?? '—'}</td>
            </tr>
            <tr>
              <th scope="row">Status</th>
              <td>{item.status ?? '—'}</td>
            </tr>
          </tbody>
        </table>
      </Card>
      {metrics.length > 0 && (
        <Card title="Related metrics">
          <table className="meta-table">
            <tbody>
              {metrics.map(([key, value]) => (
                <tr key={key}>
                  <th scope="row">{key}</th>
                  <td className="tnum">{value}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </Card>
      )}
      <Card title="Evidence">
        <Evidence evidence={item.evidence} />
      </Card>
      <p>
        <Link to="/app/insights">← Back to insights</Link>
      </p>
    </div>
  );
}
